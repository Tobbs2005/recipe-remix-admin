import Link from "next/link";
import { buttonClass, Card, ghostButtonClass, inputClass, PageHeader, Pager, Pill, Stars } from "@/components/admin/ui";
import { requireAdmin } from "@/lib/admin/auth";
import { fmtDate, recipeImageUrl } from "@/lib/admin/data";

export const metadata = { title: "AI media | Recipe Remix Admin" };
export const dynamic = "force-dynamic";

const PAGE = 36;
type Tile = { id: number; title: string; image_path: string | null; image_model: string | null; model: string; avg_rating: number; rating_count: number; created_at: string };

export default async function MediaPage({ searchParams }: { searchParams: Promise<Record<string, string | undefined>> }) {
  const { supabase } = await requireAdmin();
  const params = await searchParams;
  const q = (params.q ?? "").trim().slice(0, 80);
  const missing = params.show === "missing";
  const page = Math.max(1, Number(params.page) || 1);

  let query = supabase
    .from("recipes")
    .select("id, title, image_path, image_model, model, avg_rating, rating_count, created_at", { count: "exact" })
    .order("created_at", { ascending: false })
    .range((page - 1) * PAGE, page * PAGE - 1);
  query = missing ? query.is("image_path", null) : query.not("image_path", "is", null);
  if (q) query = query.ilike("title", `%${q.replace(/[%\\]/g, " ")}%`);

  const [{ data, count }, { count: withPhoto }, { count: withoutPhoto }] = await Promise.all([
    query,
    supabase.from("recipes").select("id", { count: "exact", head: true }).not("image_path", "is", null),
    supabase.from("recipes").select("id", { count: "exact", head: true }).is("image_path", null),
  ]);
  const tiles = (data ?? []) as Tile[];
  const pages = Math.max(1, Math.ceil((count ?? 0) / PAGE));
  const href = (p: number) => {
    const sp = new URLSearchParams();
    if (q) sp.set("q", q);
    if (missing) sp.set("show", "missing");
    if (p > 1) sp.set("page", String(p));
    const s = sp.toString();
    return s ? `/media?${s}` : "/media";
  };

  return (
    <>
      <PageHeader
        title="🖼️ AI-generated media"
        subtitle={`${withPhoto ?? 0} dish photos generated by the image step of each prompt chain · ${withoutPhoto ?? 0} recipes without a photo. Open a recipe to upload, replace or remove its photo.`}
        action={<Link href="/recipes/new" className={buttonClass}>⬆️ New recipe + upload</Link>}
      />
      <Card>
        <form className="mb-4 flex flex-wrap gap-2">
          <input name="q" defaultValue={q} placeholder="Search recipe title" className={`${inputClass} max-w-xs`} />
          <select name="show" defaultValue={missing ? "missing" : ""} className={`${inputClass} w-auto`}>
            <option value="">With photo</option>
            <option value="missing">Missing photo</option>
          </select>
          <button className="rounded-full bg-cocoa px-4 text-sm font-bold text-cream">Apply</button>
          {(q || missing) && <Link href="/media" className={ghostButtonClass}>Clear</Link>}
        </form>
        <div className="grid grid-cols-2 gap-4 sm:grid-cols-3 lg:grid-cols-4 xl:grid-cols-6">
          {tiles.map((t) => {
            const url = recipeImageUrl(t.image_path);
            return (
              <div key={t.id} className="group overflow-hidden rounded-3xl border-2 border-zinc-100 bg-white">
                {url ? (
                  <a href={url} target="_blank" rel="noreferrer" title="Open full size">
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img src={url} alt={t.title} loading="lazy" className="aspect-square w-full object-cover transition group-hover:scale-105" />
                  </a>
                ) : (
                  <div className="flex aspect-square items-center justify-center bg-zinc-100 text-3xl">📷</div>
                )}
                <div className="space-y-1 p-2.5">
                  <Link href={`/recipes/${t.id}`} className="line-clamp-2 text-sm font-bold text-cocoa hover:underline">{t.title}</Link>
                  <div className="flex items-center justify-between text-xs text-zinc-500">
                    <Stars value={Number(t.avg_rating)} size="text-xs" />
                    <span>{fmtDate(t.created_at)}</span>
                  </div>
                  {t.image_model ? <Pill tone="lilac">{t.image_model.split("/").pop()}</Pill> : url ? <Pill>uploaded</Pill> : null}
                  <Link href={`/recipes/${t.id}`} className="block text-xs font-bold text-emerald-700 hover:underline">
                    {url ? "Replace / remove →" : "Upload photo →"}
                  </Link>
                </div>
              </div>
            );
          })}
        </div>
        {!tiles.length && <p className="py-8 text-center text-sm text-zinc-500">Nothing here.</p>}
        <Pager page={page} pages={pages} href={href} />
      </Card>
    </>
  );
}
